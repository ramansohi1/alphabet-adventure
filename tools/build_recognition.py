"""Build bounded browser exemplars with Python's standard library.
These are synthetic variations of authored paths, NOT child handwriting training data.
Run after editing letters.js. --check verifies the committed output is reproducible.
"""
import argparse, json, math, pathlib, re, subprocess
ROOT = pathlib.Path(__file__).resolve().parents[1]
WEB = ROOT / 'dist' if (ROOT / 'dist').is_dir() else ROOT

def path_points(path):
    tokens = re.findall(r'[MLC]|-?\d+(?:\.\d+)?', path)
    i, p, out = 0, (0.,0.), []
    def point():
        nonlocal i
        q = tuple(map(float,tokens[i:i+2])); i += 2
        return q
    while i < len(tokens):
        op=tokens[i]; i+=1
        if op in ('M','L'):
            p=point(); out.append(p)
        elif op=='C':
            start=p; a,b,end=point(),point(),point()
            for n in range(1,81):
                t=n/80; u=1-t
                out.append(tuple(u**3*start[k]+3*u*u*t*a[k]+3*u*t*t*b[k]+t**3*end[k] for k in (0,1)))
            p=end
        else: raise ValueError(op)
    return out

def resample(points, spacing=7):
    out=[points[0]]; carry=0.
    for a,b in zip(points,points[1:]):
        d=math.dist(a,b)
        if not d: continue
        step=spacing-carry
        while step <= d:
            out.append(tuple(a[k]+(b[k]-a[k])*step/d for k in (0,1))); step+=spacing
        carry=(carry+d)%spacing
    if math.dist(out[-1],points[-1])>.1: out.append(points[-1])
    return out

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    data=json.loads(subprocess.check_output(['node','-e','console.log(JSON.stringify(require(process.argv[1])))',str(WEB/'letters.js')],text=True))
    result={}
    for kind in ('upper','lower'):
        result[kind]={}
        for letter,entry in data.items():
            strokes=[resample(path_points(p)) for p in entry[kind]]
            # Bounded width variation; no rotation or mirroring that confuses letters.
            result[kind][letter]=[[[round(x,1),round(y,1)] for x,y in s] for s in strokes]
    text='// Generated by tools/build_recognition.py; synthetic print exemplars.\nconst RECOGNITION_POINTS='+json.dumps(result,separators=(',',':'))+';\n'
    dest=WEB/'recognition-data.js'
    if args.check:
        assert dest.read_text()==text, 'Recognition data is stale; rebuild it.'
        print('PASS: 52 reproducible base print forms; six width variants applied in the browser.')
    else:
        dest.write_text(text);print('Built',dest,len(text),'bytes')
if __name__=='__main__':main()
